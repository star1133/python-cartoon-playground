import {chromium} from '@playwright/test';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const b=await chromium.launch({headless:true,args:['--no-sandbox']});
const p=await b.newPage();
p.on('console',m=>console.log('BROWSER',m.type(),m.text()));
const base=process.env.QA_URL||'http://127.0.0.1:3100';
await p.goto(base,{waitUntil:'networkidle'});
const assets=fs.readdirSync('dist/assets');
const worker='/assets/'+assets.find(x=>x.startsWith('python.worker-'));
const language='/assets/'+assets.find(x=>x.startsWith('language.worker-'));
const result=await p.evaluate(async ({worker,language})=>{
 const timeout=(ms)=>new Promise((_,reject)=>setTimeout(()=>reject(new Error('acceptance timed out')),ms));
 const w=new Worker(worker,{type:'module'}); const sab=new SharedArrayBuffer(65536); const ctrl=new Int32Array(sab,0,4);
 const messages=[]; const pending=[];
 const wait=(type)=>Promise.race([new Promise((resolve,reject)=>pending.push({type,resolve,reject})),timeout(90000)]);
 w.onmessage=e=>{messages.push(e.data); const i=pending.findIndex(x=>x.type===e.data.type||e.data.type==='error');if(i>=0){const a=pending.splice(i,1)[0];e.data.type==='error'?a.reject(new Error(e.data.error)):a.resolve(e.data);}};
 let ready=wait('init_done');w.postMessage({type:'init',sab});await ready;
 let done=wait('done');w.postMessage({type:'run',code:'import json\nprint(json.dumps({"total":sum([120,80,50])}))',mode:'normal'});await done;
 const normal=messages.filter(m=>m.type==='output').map(m=>m.text).join('');messages.length=0;
 const input=wait('input_request');done=wait('done');w.postMessage({type:'run',code:'name=input("Name: ")\nprint("Hello", name)',mode:'normal'});await input;
 const encoded=new TextEncoder().encode('แม็กซ์');new Uint8Array(sab,16).set(encoded);Atomics.store(ctrl,2,encoded.length);Atomics.store(ctrl,1,1);Atomics.notify(ctrl,1);await done;
 const inputOutput=messages.filter(m=>m.type==='output').map(m=>m.text).join('');messages.length=0;
 done=wait('done');w.postMessage({type:'run',code:'from playground_world import move_forward\nfor step in range(4):\n    move_forward()\n    print(step)',mode:'slow'});await done;
 const events=messages.filter(m=>m.type==='event').map(m=>m.event);messages.length=0;
 const installed=wait('install_done');w.postMessage({type:'install',packages:['numpy']});await installed;
 done=wait('done');w.postMessage({type:'run',code:'import numpy as np\nprint(int(np.array([1,2,3]).sum()))',mode:'normal'});await done;
 const numpy=messages.filter(m=>m.type==='output').map(m=>m.text).join('');w.terminate();
 const lw=new Worker(language,{type:'module'});const lm=[];const lp=[];
 lw.onmessage=e=>{lm.push(e.data);const i=lp.findIndex(a=>a.type===e.data.type||e.data.type==='error');if(i>=0){const a=lp.splice(i,1)[0];e.data.type==='error'?a.reject(new Error(e.data.error)):a.resolve(e.data);}};
 const lwait=type=>Promise.race([new Promise((resolve,reject)=>lp.push({type,resolve,reject})),timeout(90000)]);
 let lr=lwait('init_done');lw.postMessage({type:'init'});await lr;
 lr=lwait('complete_res');lw.postMessage({type:'complete',id:1,code:'pri',line:1,column:4});const pri=await lr;
 lr=lwait('complete_res');lw.postMessage({type:'complete',id:2,code:'import math\nmath.',line:2,column:6});const math=await lr;
 lw.terminate();return {normal,inputOutput,events,numpy,pri,math};
},{worker,language});
assert.match(result.normal,/"total": 250/);assert.match(result.inputOutput,/Hello แม็กซ์/);assert.match(result.numpy,/6/);
assert.ok(result.events.length>10);assert.ok(result.events.some(e=>e.world?.x===4));assert.ok(result.events.some(e=>e.kind==='stdout'));
assert.equal(new Set(result.events.map(e=>e.seq)).size,result.events.length);
fs.writeFileSync('.runtime/acceptance.json',JSON.stringify(result,null,2));console.log(JSON.stringify({normal:result.normal,input:result.inputOutput,numpy:result.numpy,eventCount:result.events.length,pri:result.pri,math:result.math},null,2));
await b.close();
