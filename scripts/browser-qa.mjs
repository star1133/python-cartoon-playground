import { chromium } from '@playwright/test';
import fs from 'node:fs';
const browser = await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
const base=process.env.QA_URL||'http://127.0.0.1:3100';
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];const requests=[];
page.on('pageerror',e=>errors.push(String(e)));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
page.on('request',r=>{if(r.method()!=='GET')requests.push({url:r.url(),method:r.method()});});
await page.goto(base,{waitUntil:'networkidle',timeout:120000});
await page.getByRole('button',{name:'รันโค้ด Python',exact:true}).click();
await page.waitForFunction(()=>document.body.innerText.includes('การทำงานเสร็จสมบูรณ์')||document.body.innerText.includes('[ระบบ] ข้อผิดพลาด'),{timeout:120000});
console.log('RUN',await page.locator('body').innerText());
console.log('ISOLATION',await page.evaluate(()=>crossOriginIsolated));
console.log('ERRORS',JSON.stringify(errors));
console.log('NON_GET',JSON.stringify(requests));
fs.mkdirSync('.impeccable/review',{recursive:true});
await page.screenshot({path:'.impeccable/review/desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(1000);
await page.screenshot({path:'.impeccable/review/mobile.png',fullPage:true});
console.log('MOBILE',await page.evaluate(()=>({w:innerWidth,scroll:document.documentElement.scrollWidth,text:document.body.innerText.slice(0,1500)})));
await browser.close();
