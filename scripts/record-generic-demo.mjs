import {chromium} from '@playwright/test';
import fs from 'node:fs';
const out='/tmp/python-playground-qa/python-generic-demo';fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({args:['--no-sandbox','--enable-unsafe-swiftshader']});
const context=await browser.newContext({viewport:{width:1440,height:900},recordVideo:{dir:out,size:{width:1440,height:900}}});
const page=await context.newPage();const errors=[];
page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
const code=`prices = [120, 80, 50]\ntotal = 0\n\nfor price in prices:\n    total += price\n\nprint("Total:", total)\n`;
await page.addInitScript(c=>localStorage.setItem('python_playground_draft_code',c),code);
await page.goto(process.env.QA_URL||'http://127.0.0.1:3100',{waitUntil:'networkidle',timeout:120000});
await page.waitForTimeout(1500);
await page.getByRole('button',{name:'รันโค้ด Python',exact:true}).click();
await page.waitForFunction(()=>document.body.innerText.includes('Total: 250'),null,{timeout:120000});
await page.waitForTimeout(1500);
await page.getByRole('button',{name:'ตัวแปร (Variables)',exact:true}).click();
await page.screenshot({path:out+'/generic-variables.png'});
await page.waitForTimeout(2500);
await page.getByTitle('ขั้นตอนแรกสุด',{exact:true}).click();
await page.waitForTimeout(1500);
await page.getByTitle('ก้าวไปข้างหน้า 1 ขั้น',{exact:true}).click();await page.waitForTimeout(1500);
await page.getByTitle('ขั้นตอนล่าสุด',{exact:true}).click();await page.waitForTimeout(1500);
const functionCode=`def square(number):\n    result = number * number\n    return result\n\nx = 7\nanswer = square(x)\nprint("Square:", answer)\n`;
await page.locator('input[type="file"]').setInputFiles({name:'square.py',mimeType:'text/x-python',buffer:Buffer.from(functionCode)});
await page.getByRole('button',{name:'คอนโซล (Console)',exact:true}).click();
await page.getByRole('button',{name:'รันโค้ด Python',exact:true}).click();
await page.waitForFunction(()=>document.body.innerText.includes('Square: 49'),null,{timeout:120000});
await page.waitForTimeout(2000);
await page.getByRole('button',{name:'ตัวแปร (Variables)',exact:true}).click();await page.waitForTimeout(2000);
await page.screenshot({path:out+'/function-variables.png'});
fs.writeFileSync(out+'/evidence.json',JSON.stringify({errors,text:await page.locator('body').innerText(),code,functionCode},null,2));
const video=page.video();await context.close();await browser.close();console.log('VIDEO',await video.path());console.log('ERRORS',errors);
