import { chromium } from '@playwright/test';
import fs from 'node:fs';
const out='/tmp/python-playground-qa/python-playground-demo';
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
const context=await browser.newContext({viewport:{width:1280,height:800},recordVideo:{dir:out,size:{width:1280,height:800}}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const base=process.env.QA_URL||'http://127.0.0.1:3100';
const world=`from playground_world import move_forward\n\nfor step in range(4):\n    move_forward()\n    print(f"Walking step {step}")\n`;
await page.addInitScript(code=>localStorage.setItem('python_playground_draft_code',code),world);
await page.goto(base,{waitUntil:'networkidle',timeout:120000});
await page.waitForTimeout(2000);
await page.getByRole('button',{name:'รันโค้ด Python',exact:true}).click();
await page.waitForFunction(()=>Number(document.querySelector('input[type="range"]')?.max)>0, null, {timeout:120000});
await page.waitForFunction(()=>document.body.innerText.includes('Walking step 3'),null,{timeout:120000});
await page.waitForTimeout(2500);
const worldText=await page.locator('body').innerText();
if(!worldText.includes('Walking step 3')||worldText.includes('ยังไม่มีประวัติ'))throw new Error('World run lacks real trace/output');
await page.screenshot({path:out+'/world.png'});
await page.getByTitle('ขั้นตอนแรกสุด').click();
await page.waitForTimeout(1500);
await page.getByTitle('ก้าวไปข้างหน้า 1 ขั้น', {exact:true}).click();
await page.waitForTimeout(1000);
await page.getByTitle('ขั้นตอนล่าสุด').click();
await page.waitForTimeout(1500);
const code=`import json\n\ndef calculate_total(prices):\n    total = 0\n    for price in prices:\n        total += price\n    return total\n\nprices = [120, 80, 50]\nresult = {"items": len(prices), "total": calculate_total(prices)}\nprint(json.dumps(result))\n`;
await page.locator('input[type="file"]').setInputFiles({name:'shopping_total.py',mimeType:'text/x-python',buffer:Buffer.from(code)});
await page.waitForTimeout(1500);
await page.getByRole('button',{name:'รันปกติ',exact:true}).click();
await page.getByRole('button',{name:'รันโค้ด Python',exact:true}).click();
await page.waitForFunction(()=>document.body.innerText.includes('"total": 250'),null,{timeout:120000});
await page.waitForTimeout(2500);
await page.getByRole('button',{name:'แอนิเมชันทีละขั้น',exact:true}).click();
await page.getByLabel('เลือกความเร็วแอนิเมชัน').selectOption('2');
await page.getByRole('button',{name:'รันโค้ด Python',exact:true}).click();
await page.waitForFunction(()=>document.body.innerText.includes('"total": 250'),null,{timeout:120000});
await page.getByRole('button',{name:'ตัวแปร (Variables)',exact:true}).click();
await page.waitForTimeout(3000);
const finalText=await page.locator('body').innerText();
await page.screenshot({path:out+'/variables.png'});
fs.writeFileSync(out+'/evidence.json',JSON.stringify({base,worldText,finalText,errors},null,2));
const video=page.video();
await context.close();await browser.close();
console.log('VIDEO',await video.path());
console.log('ERRORS',JSON.stringify(errors));
